    #[test]
    fn instances_have_separate_mutable_fields_and_safe_field_symbols() {
        let this = || variable("__tsh_this", Type::Class("Counter".to_owned()));
        let this_count = || {
            expr(
                ExprKind::Field {
                    object: Box::new(this()),
                    class: "Counter".to_owned(),
                    field: "x-y;$(touch BAD)".to_owned(),
                },
                Type::Number,
            )
        };
        let increment = Function {
            name: "increment".to_owned(),
            params: vec![],
            return_type: Type::Number,
            body: vec![
                Stmt::Assign {
                    place: Place::Field {
                        object: this(),
                        class: "Counter".to_owned(),
                        field: "x-y;$(touch BAD)".to_owned(),
                    },
                    value: expr(
                        ExprKind::Binary {
                            op: "+".to_owned(),
                            left: Box::new(this_count()),
                            right: Box::new(number(1)),
                        },
                        Type::Number,
                    ),
                },
                Stmt::Return(Some(this_count())),
            ],
        };
        let class = Class {
            name: "Counter".to_owned(),
            fields: vec![Field {
                name: "x-y;$(touch BAD)".to_owned(),
                ty: Type::Number,
                initial: Some(number(4)),
            }],
            constructor: Function {
                name: "Counter".to_owned(),
                params: vec![],
                return_type: Type::Void,
                body: vec![],
            },
            methods: vec![Method {
                function: increment,
                is_static: false,
            }],
        };
        let instance = |name: &str| variable(name, Type::Class("Counter".to_owned()));
        let field = |name: &str| {
            expr(
                ExprKind::Field {
                    object: Box::new(instance(name)),
                    class: "Counter".to_owned(),
                    field: "x-y;$(touch BAD)".to_owned(),
                },
                Type::Number,
            )
        };
        let call_increment = |name: &str| {
            expr(
                ExprKind::Method {
                    object: Some(Box::new(instance(name))),
                    class: "Counter".to_owned(),
                    method: "increment".to_owned(),
                    args: vec![],
                },
                Type::Number,
            )
        };
        let program = Program {
            classes: vec![class],
            body: vec![
                Stmt::Let {
                    name: "first".to_owned(),
                    value: expr(
                        ExprKind::New {
                            class: "Counter".to_owned(),
                            args: vec![],
                        },
                        Type::Class("Counter".to_owned()),
                    ),
                },
                Stmt::Let {
                    name: "second".to_owned(),
                    value: expr(
                        ExprKind::New {
                            class: "Counter".to_owned(),
                            args: vec![],
                        },
                        Type::Class("Counter".to_owned()),
                    ),
                },
                Stmt::Expr(call_increment("first")),
                command(Command::Echo, vec![field("second"), field("first")], false),
            ],
            ..Program::default()
        };
        let script = Bash.emit(&program).expect("emit class");
        assert!(!script.contains("x-y;$(touch BAD)"));
        assert!(!script.contains("touch BAD"));
        let output = run_bash(&script, None);
        assert!(
            output.status.success(),
            "{}",
            String::from_utf8_lossy(&output.stderr)
        );
        assert_eq!(String::from_utf8_lossy(&output.stdout), "4 5\n");
    }

