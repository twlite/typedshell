    #[cfg(unix)]
    #[test]
    fn filesystem_commands_quote_leading_dash_operands_and_preserve_status() {
        use std::os::unix::fs::PermissionsExt;

        let temp = tempfile::tempdir().expect("temporary directory");
        let path = temp.path().to_string_lossy().into_owned();
        let program = Program {
            body: vec![
                command(Command::Cd, vec![string(&path)], false),
                command(Command::Mkdir, vec![string("-p/nested")], true),
                command(
                    Command::Run,
                    vec![string("touch"), string("--"), string("-f")],
                    false,
                ),
                command(Command::Mv, vec![string("-f"), string("-g")], false),
                command(Command::Cp, vec![string("-g"), string("-h")], false),
                command(Command::Chmod, vec![string("-h"), number(493)], false),
                command(Command::Rm, vec![string("-g")], false),
                command(Command::Rm, vec![string("-p")], true),
            ],
            ..Program::default()
        };
        let script = Bash.emit(&program).expect("emit filesystem commands");
        assert!(script.contains("mkdir -p --"));
        assert!(script.contains("mv --"));
        assert!(script.contains("cp --"));
        assert!(script.contains("chmod --"));
        let output = run_bash(&script, None);
        assert!(
            output.status.success(),
            "{}",
            String::from_utf8_lossy(&output.stderr)
        );
        assert_eq!(
            std::fs::metadata(temp.path().join("-h"))
                .expect("chmod target")
                .permissions()
                .mode()
                & 0o777,
            0o755
        );
        assert!(!temp.path().join("-p").exists());
        assert!(!temp.path().join("-g").exists());
    }

